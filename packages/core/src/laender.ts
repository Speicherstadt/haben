const BEKANNT: ReadonlySet<string> = new Set(LAENDER);
const namen = new Map<string, Intl.DisplayNames>();

/** Name des Landes in der Sprache `sprache`; einen Code, den Intl nicht kennt, unverändert */
export function landName(code: string, sprache = "de"): string {
  // Nur Codes der Liste: Intl nennt etwa „ZZ“ „Unbekannte Region“, gespeichert ist aber genau dieser Code
  if (!BEKANNT.has(code)) return code;
  let anzeige = namen.get(sprache);
  if (!anzeige) {
    anzeige = new Intl.DisplayNames([sprache], { type: "region", fallback: "code" });
    namen.set(sprache, anzeige);
  }
  try {
    return anzeige.of(code) ?? code;
  } catch {
    return code;
  }
}

/**
 * Länder zur Auswahl, nach Name sortiert. Ein gespeicherter Code, der nicht in der Liste steht, etwa aus einem Import,
 * kommt dazu: Er bleibt so wählbar und wird beim Speichern nicht still ersetzt.
 */
export function laenderAuswahl(gespeichert?: string, sprache = "de"): { code: string; name: string }[] {
  const codes: string[] = [...LAENDER];
  if (gespeichert && !codes.includes(gespeichert)) codes.push(gespeichert);
  return codes.map((code) => ({ code, name: landName(code, sprache) })).sort((a, b) => a.name.localeCompare(b.name, sprache));
}

/**
 * Prüfung der PLZ je Land: in Deutschland genau fünf Ziffern, sonst freier Text (Buchstaben und Leerzeichen, etwa
 * „SW1A 1AA“ oder „1015 CJ“). Eine Prüfung weiterer Länder kommt erst, wenn jemand sie braucht (#914). Leer ist erlaubt.
 */
export function plzProblem(land: string, plz: string): string | null {
  const wert = plz.trim();
  if (wert === "" || land !== "DE") return null;
  return /^\d{5}$/.test(wert) ? null : "Eine deutsche PLZ hat fünf Ziffern, etwa 93047.";
}
